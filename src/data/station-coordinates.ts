export interface StaticStationLocation {
  latitude: number;
  longitude: number;
}

const LOCATIONS = new Map<string, StaticStationLocation>();

function add(lineId: string, stationName: string, latitude: number, longitude: number): void {
  LOCATIONS.set(`${lineId}:${stationName}`, { latitude, longitude });
}

